String tr(BuildContext context, String key, [Map<String, String>? params]) {
  final loc = AppLocalizations.of(context);
  var s = loc.get(key);
  if (params != null) { params.forEach((k, v) { s = s.replaceAll('{$k}', v); }); }
  return s;
}

/// Choisit entre `<cle>_one` et `<cle>_many` selon `n`, et fournit `{n}`.
///
/// ⚠️ `_many` ET NON `_other` : le catalogue portait DÉJÀ cette convention
/// (`colleagues_count_none` / `_one` / `_many`, écrite à la main dans deux
/// écrans). Introduire un second suffixe pour la même idée aurait laissé deux
/// façons de nommer un pluriel dans le même fichier — la prochaine personne
/// aurait eu à deviner laquelle. Le `_none` reste facultatif : les écrans qui
/// distinguent le zéro le traitent eux-mêmes, avant d'appeler `trN`.
///
/// 🔴 LA RÈGLE DU PLURIEL ÉTAIT ÉCRITE DANS LES ÉCRANS, en dur et en français :
/// `"$n contact${n > 1 ? 's' : ''}"`. Ce `s` ne se traduit pas — il n'a de sens
/// qu'en français, et la forme est FIGÉE dans le code, hors de portée du
/// catalogue. Chaque langue doit pouvoir écrire ses deux formes en entier.
///
/// ⚠️ DEUX FORMES, PAS PLUS. Cela couvre le français, l'anglais, l'allemand,
/// l'espagnol, le portugais, le suédois et le norvégien. Le CHINOIS n'en a
/// qu'une : ses deux entrées y sont identiques, ce qui est correct. Le RUSSE en
/// compte TROIS (1 / 2-4 / 5+) : sa forme `_many` reste donc approximative sur
/// les petits nombres. Le corriger demanderait une vraie table de pluriels
/// (`intl` et ses règles CLDR), disproportionné pour les quelques compteurs
/// concernés — mais c'est la limite à connaître.
String trN(BuildContext context, String cle, int n,
    [Map<String, String>? params]) {
  return tr(context, '$cle${n > 1 ? '_many' : '_one'}', {
    ...?params,
    'n': '$n',
  });
}
